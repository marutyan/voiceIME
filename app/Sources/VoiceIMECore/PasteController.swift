/// `AXUIElement` 等の `CFTypeRef` を `CFEqual` で値比較するための安全なラッパー。
public final class FocusedElementHandle: @unchecked Sendable, Equatable {
    public let rawValue: CFTypeRef

    public init(_ rawValue: CFTypeRef) {
        self.rawValue = rawValue
    }

    public static func == (lhs: FocusedElementHandle, rhs: FocusedElementHandle) -> Bool {
        CFEqual(lhs.rawValue, rhs.rawValue)
    }
}

/// 録音開始時点の入力先（前面アプリのPIDとアクセシビリティのフォーカス要素）。
public struct PasteTarget: Sendable, Equatable {
    public let pid: pid_t
    public let bundleId: String?
    public let appName: String?
    public let focusedElement: FocusedElementHandle?

    public init(
        pid: pid_t,
        bundleId: String? = nil,
        appName: String? = nil,
        focusedElement: FocusedElementHandle? = nil
    ) {
        self.pid = pid
        self.bundleId = bundleId
        self.appName = appName
        self.focusedElement = focusedElement
    }

    /// 認識エンジンの `start` メッセージへ渡すアプリ情報を組み立てる。
    public var appInfo: TargetAppInfo {
        TargetAppInfo(bundleId: bundleId ?? "", name: appName ?? "")
    }

    /// PIDとフォーカス中のUI要素が一致するか判定する。両方とも要素取得不可の場合はPID一致で同一とみなす。
    public func matches(_ other: PasteTarget) -> Bool {
        pid == other.pid && focusedElement == other.focusedElement
    }
}

/// ペーストボード1要素内の「データ種別とバイト列」の組。
public struct PasteboardEntry: Sendable, Equatable {
    public let type: String
    public let data: Data

    public init(type: String, data: Data) {
        self.type = type
        self.data = data
    }
}

/// 退避した1つの `NSPasteboardItem` の全typeデータ。
public struct PasteboardItemSnapshot: Sendable, Equatable {
    public let entries: [PasteboardEntry]

    public init(entries: [PasteboardEntry]) {
        self.entries = entries
    }
}

/// ペーストボード全体の退避スナップショット。
public struct PasteboardSnapshot: Sendable, Equatable {
    public let items: [PasteboardItemSnapshot]

    public init(items: [PasteboardItemSnapshot]) {
        self.items = items
    }

    public var isEmpty: Bool { items.isEmpty }
}

/// クリップボード履歴ツールへの記録を避けるために付与する標準マーカーUTI。
public enum PasteboardMarker {
    public static let transientType = "org.nspasteboard.TransientType"
    public static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"
    public static let stringType = NSPasteboard.PasteboardType.string.rawValue
}

/// クリップボード読み書きの抽象インターフェース。テストではインメモリ実装へ差し替える。
@MainActor
public protocol PasteboardClient: AnyObject {
    var changeCount: Int { get }
    func snapshot() -> PasteboardSnapshot
    @discardableResult
    func writeTransientText(_ text: String) -> Bool
    @discardableResult
    func writePlainText(_ text: String) -> Bool
    @discardableResult
    func restore(_ snapshot: PasteboardSnapshot) -> Bool
}

/// `NSPasteboard` を使う標準のクリップボード実装。全itemの全typeデータをそのまま退避・復元する。
@MainActor
public final class SystemPasteboardClient: PasteboardClient {
    private let pasteboard: NSPasteboard

    public init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    public var changeCount: Int {
        pasteboard.changeCount
    }

    public func snapshot() -> PasteboardSnapshot {
        guard let items = pasteboard.pasteboardItems else {
            return PasteboardSnapshot(items: [])
        }
        let capturedItems: [PasteboardItemSnapshot] = items.map { item in
            let entries: [PasteboardEntry] = item.types.compactMap { type in
                guard let data = item.data(forType: type) else { return nil }
                return PasteboardEntry(type: type.rawValue, data: data)
            }
            return PasteboardItemSnapshot(entries: entries)
        }.filter { !$0.entries.isEmpty }
        return PasteboardSnapshot(items: capturedItems)
    }

    @discardableResult
    public func writeTransientText(_ text: String) -> Bool {
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // クリップボード履歴アプリに一時的な貼り付けデータが残らないよう標準マーカーを付与する。
        item.setData(Data(), forType: NSPasteboard.PasteboardType(PasteboardMarker.transientType))
        item.setData(Data(), forType: NSPasteboard.PasteboardType(PasteboardMarker.autoGeneratedType))
        pasteboard.clearContents()
        return pasteboard.writeObjects([item])
    }

    @discardableResult
    public func writePlainText(_ text: String) -> Bool {
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        pasteboard.clearContents()
        return pasteboard.writeObjects([item])
    }

    @discardableResult
    public func restore(_ snapshot: PasteboardSnapshot) -> Bool {
        pasteboard.clearContents()
        guard !snapshot.isEmpty else {
            return true
        }
        let objects: [NSPasteboardItem] = snapshot.items.map { itemSnapshot in
            let item = NSPasteboardItem()
            for entry in itemSnapshot.entries {
                item.setData(entry.data, forType: NSPasteboard.PasteboardType(entry.type))
            }
            return item
        }
        return pasteboard.writeObjects(objects)
    }
}

/// 現在の前面アプリとフォーカス要素を取得する抽象インターフェース。
@MainActor
public protocol TargetProviding: AnyObject {
    func currentTarget() -> PasteTarget?
}

/// `NSWorkspace` と `AXUIElement` を使って現在の入力先を取得する実装。
@MainActor
public final class SystemTargetProvider: TargetProviding {
    public init() {}

    public func currentTarget() -> PasteTarget? {
        guard let app = NSWorkspace.shared.frontmostApplication else {
            return nil
        }
        let pid = app.processIdentifier
        guard pid > 0 else {
            return nil
        }

        // アプリによってはAXFocusedUIElementを返さないため、失敗時はnilとしてPID一致で照合する。
        let axApp = AXUIElementCreateApplication(pid)
        var focusedValue: CFTypeRef?
        let status = AXUIElementCopyAttributeValue(
            axApp,
            kAXFocusedUIElementAttribute as CFString,
            &focusedValue
        )
        let focusedHandle: FocusedElementHandle?
        if status == .success, let focusedValue {
            focusedHandle = FocusedElementHandle(focusedValue)
        } else {
            focusedHandle = nil
        }

        return PasteTarget(
            pid: pid,
            bundleId: app.bundleIdentifier,
            appName: app.localizedName,
            focusedElement: focusedHandle
        )
    }
}

/// 修飾キー状態の確認と⌘Vイベント送信の抽象インターフェース。
@MainActor
public protocol PasteInputDriver: AnyObject {
    func areModifiersPressed() -> Bool
    func sendCommandV() -> Bool
}

/// CoreGraphicsイベントAPIで修飾キー確認と⌘V送信を行う標準実装。
@MainActor
public final class SystemPasteInputDriver: PasteInputDriver {
    private static let keyCodeV: CGKeyCode = 0x09

    public init() {}

    public func areModifiersPressed() -> Bool {
        let flags = CGEventSource.flagsState(.combinedSessionState)
        let watched: CGEventFlags = [
            .maskCommand,
            .maskControl,
            .maskAlternate,
            .maskShift,
            .maskSecondaryFn,
        ]
        return !flags.intersection(watched).isEmpty
    }

    public func sendCommandV() -> Bool {
        // アクセシビリティ権限が無い場合、CGEvent.postはエラーを返さず黙って捨てられるため事前に確認する。
        guard AXIsProcessTrusted() else {
            return false
        }
        guard let keyDown = CGEvent(keyboardEventSource: nil, virtualKey: Self.keyCodeV, keyDown: true),
              let keyUp = CGEvent(keyboardEventSource: nil, virtualKey: Self.keyCodeV, keyDown: false) else {
            return false
        }
        keyDown.flags = .maskCommand
        keyUp.flags = .maskCommand
        keyDown.post(tap: .cghidEventTap)
        keyUp.post(tap: .cghidEventTap)
        return true
    }
}

/// 貼り付けを行わずクリップボードへのコピーにフォールバックした理由。
public enum PasteFallbackReason: Sendable, Equatable {
    case targetChanged
    case modifiersTimeout
    case clipboardOverwrittenBeforePaste
    case pasteCommandFailed
    case clipboardWriteFailed

    public var userMessage: String {
        switch self {
        case .targetChanged:
            return "入力先またはフォーカスが変わったため貼り付けを中止し、結果をクリップボードへコピーしました。"
        case .modifiersTimeout:
            return "修飾キーが押されたままだったため貼り付けを中止し、結果をクリップボードへコピーしました。"
        case .clipboardOverwrittenBeforePaste:
            return "貼り付け直前に別のアプリがクリップボードを変更したため、貼り付けを中止しました。"
        case .pasteCommandFailed:
            return "⌘Vの送信に失敗したため、結果をクリップボードへコピーしました。アクセシビリティ権限を確認してください。"
        case .clipboardWriteFailed:
            return "クリップボードへの書き込みに失敗しました。"
        }
    }

    /// オーバーレイの狭いエラーピル（最大248pt・1行）に収める短い理由文。
    public var overlayMessage: String {
        switch self {
        case .targetChanged:
            return "入力先変更：コピーしました"
        case .modifiersTimeout:
            return "修飾キー押下中：コピーしました"
        case .clipboardOverwrittenBeforePaste:
            return "クリップボード変更：中止しました"
        case .pasteCommandFailed:
            return "貼り付け失敗：コピーしました"
        case .clipboardWriteFailed:
            return "クリップボード書き込み失敗"
        }
    }
}

/// 貼り付けトランザクションの結果。
public enum PasteOutcome: Sendable, Equatable {
    case skippedEmpty
    case pasted(restoredClipboard: Bool)
    case copiedFallback(reason: PasteFallbackReason)
}

/// 宛先照合・修飾キー解放待ち・クリップボード退避/復元を伴う安全な⌘V貼り付けコントローラ。
@MainActor
public final class PasteController {
    private let pasteboard: PasteboardClient
    private let targetProvider: TargetProviding
    private let inputDriver: PasteInputDriver
    private let modifierPollInterval: Duration
    private let modifierWaitTimeout: Duration
    private let restoreDelay: Duration

    public init(
        pasteboard: PasteboardClient = SystemPasteboardClient(),
        targetProvider: TargetProviding = SystemTargetProvider(),
        inputDriver: PasteInputDriver = SystemPasteInputDriver(),
        modifierPollInterval: Duration = .milliseconds(20),
        modifierWaitTimeout: Duration = .seconds(2),
        restoreDelay: Duration = .milliseconds(250)
    ) {
        self.pasteboard = pasteboard
        self.targetProvider = targetProvider
        self.inputDriver = inputDriver
        self.modifierPollInterval = modifierPollInterval
        self.modifierWaitTimeout = modifierWaitTimeout
        self.restoreDelay = restoreDelay
    }

    /// 録音開始時の宛先スナップショットを取得する。
    public func captureTarget() -> PasteTarget? {
        targetProvider.currentTarget()
    }

    /// 文字列をクリップボードへ通常コピーする。
    @discardableResult
    public func copyToClipboard(_ text: String) -> Bool {
        pasteboard.writePlainText(text)
    }

    /// `expectedTarget` を照合したうえで一時データとして貼り付け、外部更新が無ければ元のクリップボードを復元する。
    /// `expectedTarget` が `nil` の場合（「最後の結果をもう一度貼る」など）は現在の前面アプリへそのまま貼る。
    public func paste(text: String, expectedTarget: PasteTarget?) async -> PasteOutcome {
        let sanitized = text.replacingOccurrences(of: "\0", with: "")
        guard !sanitized.isEmpty else {
            return .skippedEmpty
        }

        if let expectedTarget, !isCurrentTargetMatching(expectedTarget) {
            pasteboard.writePlainText(sanitized)
            return .copiedFallback(reason: .targetChanged)
        }

        // 修飾キーが押されたままだと⌘Vが別ショートカットへ化けるため、離されるまで待機する。
        let modifiersCleared = await waitForModifiersToClear()
        if !modifiersCleared {
            pasteboard.writePlainText(sanitized)
            return .copiedFallback(reason: .modifiersTimeout)
        }

        if let expectedTarget, !isCurrentTargetMatching(expectedTarget) {
            pasteboard.writePlainText(sanitized)
            return .copiedFallback(reason: .targetChanged)
        }

        let previousSnapshot = pasteboard.snapshot()
        let changeCountBefore = pasteboard.changeCount
        guard pasteboard.writeTransientText(sanitized) else {
            return .copiedFallback(reason: .clipboardWriteFailed)
        }
        let changeCountOurs = pasteboard.changeCount

        if let expectedTarget, !isCurrentTargetMatching(expectedTarget) {
            if pasteboard.changeCount == changeCountOurs {
                pasteboard.writePlainText(sanitized)
            }
            return .copiedFallback(reason: .targetChanged)
        }

        if pasteboard.changeCount != changeCountOurs {
            return .copiedFallback(reason: .clipboardOverwrittenBeforePaste)
        }

        guard inputDriver.sendCommandV() else {
            if pasteboard.changeCount == changeCountOurs {
                pasteboard.writePlainText(sanitized)
            }
            return .copiedFallback(reason: .pasteCommandFailed)
        }

        // 貼り付け先アプリが非同期にペーストボードを読み終えるまで待ってから復元判定する。
        if restoreDelay > .zero {
            try? await Task.sleep(for: restoreDelay)
        }

        let shouldRestore = (changeCountOurs != changeCountBefore)
            && (pasteboard.changeCount == changeCountOurs)
        if shouldRestore {
            let restored = pasteboard.restore(previousSnapshot)
            return .pasted(restoredClipboard: restored)
        }
        return .pasted(restoredClipboard: false)
    }

    private func isCurrentTargetMatching(_ expected: PasteTarget) -> Bool {
        guard let current = targetProvider.currentTarget() else {
            return false
        }
        return expected.matches(current)
    }

    private func waitForModifiersToClear() async -> Bool {
        guard inputDriver.areModifiersPressed() else {
            return true
        }
        let clock = ContinuousClock()
        let deadline = clock.now.advanced(by: modifierWaitTimeout)
        while inputDriver.areModifiersPressed() {
            if clock.now >= deadline {
                return false
            }
            try? await Task.sleep(for: modifierPollInterval)
        }
        return true
    }
}
