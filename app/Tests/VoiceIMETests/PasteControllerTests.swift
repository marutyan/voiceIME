import XCTest
@testable import VoiceIMECore

/// テスト用のインメモリクリップボード。`changeCount` の変化や一時マーカー付与・全type復元を厳密に観測できる。
@MainActor
final class MockPasteboardClient: PasteboardClient {
    var changeCount: Int = 1
    var currentSnapshot: PasteboardSnapshot
    var writtenSnapshotsHistory: [PasteboardSnapshot] = []
    var shouldFailTransientWrite = false
    var onWriteTransient: (() -> Void)?

    init(initialSnapshot: PasteboardSnapshot = PasteboardSnapshot(items: [])) {
        self.currentSnapshot = initialSnapshot
    }

    func snapshot() -> PasteboardSnapshot {
        currentSnapshot
    }

    @discardableResult
    func writeTransientText(_ text: String) -> Bool {
        if shouldFailTransientWrite {
            return false
        }
        let item = PasteboardItemSnapshot(entries: [
            PasteboardEntry(type: "public.utf8-plain-text", data: Data(text.utf8)),
            PasteboardEntry(type: "org.nspasteboard.TransientType", data: Data()),
            PasteboardEntry(type: "org.nspasteboard.AutoGeneratedType", data: Data()),
        ])
        currentSnapshot = PasteboardSnapshot(items: [item])
        changeCount += 1
        writtenSnapshotsHistory.append(currentSnapshot)
        onWriteTransient?()
        return true
    }

    @discardableResult
    func writePlainText(_ text: String) -> Bool {
        let item = PasteboardItemSnapshot(entries: [
            PasteboardEntry(type: "public.utf8-plain-text", data: Data(text.utf8)),
        ])
        currentSnapshot = PasteboardSnapshot(items: [item])
        changeCount += 1
        writtenSnapshotsHistory.append(currentSnapshot)
        return true
    }

    @discardableResult
    func restore(_ snapshot: PasteboardSnapshot) -> Bool {
        currentSnapshot = snapshot
        changeCount += 1
        writtenSnapshotsHistory.append(snapshot)
        return true
    }

    /// 他アプリによる外部コピーを模擬し、`changeCount` を進める。
    func simulateExternalCopy(text: String) {
        let item = PasteboardItemSnapshot(entries: [
            PasteboardEntry(type: "public.utf8-plain-text", data: Data(text.utf8)),
        ])
        currentSnapshot = PasteboardSnapshot(items: [item])
        changeCount += 1
    }
}

/// テスト用の宛先プロバイダ。
@MainActor
final class MockTargetProvider: TargetProviding {
    var target: PasteTarget?
    var onQuery: ((Int) -> Void)?
    private var queryCount = 0

    init(target: PasteTarget?) {
        self.target = target
    }

    func currentTarget() -> PasteTarget? {
        queryCount += 1
        onQuery?(queryCount)
        return target
    }
}

/// テスト用の修飾キー・⌘Vドライバ。
@MainActor
final class MockPasteInputDriver: PasteInputDriver {
    var modifierPollResponses: [Bool] = []
    var defaultModifiersPressed = false
    var sendCommandVResult = true
    var sendCommandVCallCount = 0
    var onSendCommandV: (() -> Void)?

    func areModifiersPressed() -> Bool {
        if !modifierPollResponses.isEmpty {
            return modifierPollResponses.removeFirst()
        }
        return defaultModifiersPressed
    }

    func sendCommandV() -> Bool {
        sendCommandVCallCount += 1
        onSendCommandV?()
        return sendCommandVResult
    }
}

/// クリップボード退避・一時データ印・`changeCount`による復元判定・宛先照合・修飾キー待機を検証するテスト。
@MainActor
final class PasteControllerTests: XCTestCase {
    private func makeElement(_ id: String) -> FocusedElementHandle {
        FocusedElementHandle(id as CFString)
    }

    func testPasteBacksUpAllTypesAddsTransientMarkersAndRestoresWhenUnchanged() async {
        let original = PasteboardSnapshot(items: [
            PasteboardItemSnapshot(entries: [
                PasteboardEntry(type: "public.utf8-plain-text", data: Data("元のテキスト".utf8)),
                PasteboardEntry(type: "public.rtf", data: Data("{\\rtf1 original}".utf8)),
                PasteboardEntry(type: "com.example.custom", data: Data([0xDE, 0xAD, 0xBE, 0xEF])),
            ]),
            PasteboardItemSnapshot(entries: [
                PasteboardEntry(type: "public.html", data: Data("<p>2件目</p>".utf8)),
            ]),
        ])
        let board = MockPasteboardClient(initialSnapshot: original)
        let target = PasteTarget(pid: 100, bundleId: "com.apple.dt.Xcode", appName: "Xcode", focusedElement: makeElement("editor-1"))
        let targetProvider = MockTargetProvider(target: target)
        let driver = MockPasteInputDriver()

        var snapshotDuringPaste: PasteboardSnapshot?
        driver.onSendCommandV = {
            snapshotDuringPaste = board.currentSnapshot
        }

        let controller = PasteController(
            pasteboard: board,
            targetProvider: targetProvider,
            inputDriver: driver,
            modifierPollInterval: .milliseconds(5),
            modifierWaitTimeout: .milliseconds(100),
            restoreDelay: .milliseconds(10)
        )

        let outcome = await controller.paste(text: "PyTorchのDataLoaderで", expectedTarget: target)
        XCTAssertEqual(outcome, .pasted(restoredClipboard: true))
        XCTAssertEqual(driver.sendCommandVCallCount, 1)

        // ⌘V送信時のペーストボードに文字列と一時データ印の両方が入っていること。
        let pastedEntries = snapshotDuringPaste?.items.first?.entries ?? []
        XCTAssertEqual(
            pastedEntries.first(where: { $0.type == "public.utf8-plain-text" })?.data,
            Data("PyTorchのDataLoaderで".utf8)
        )
        XCTAssertNotNil(pastedEntries.first(where: { $0.type == "org.nspasteboard.TransientType" }))
        XCTAssertNotNil(pastedEntries.first(where: { $0.type == "org.nspasteboard.AutoGeneratedType" }))

        // 復元後は全item・全typeが完全に元に戻っていること。
        XCTAssertEqual(board.currentSnapshot, original)
    }

    func testDoesNotRestoreClipboardIfExternalAppCopiedDuringPaste() async {
        let original = PasteboardSnapshot(items: [
            PasteboardItemSnapshot(entries: [
                PasteboardEntry(type: "public.utf8-plain-text", data: Data("古いコピー".utf8)),
            ]),
        ])
        let board = MockPasteboardClient(initialSnapshot: original)
        let target = PasteTarget(pid: 200, focusedElement: makeElement("field-A"))
        let targetProvider = MockTargetProvider(target: target)
        let driver = MockPasteInputDriver()
        driver.onSendCommandV = {
            // ⌘V直後に他アプリが新しくコピーした状況を模擬する。
            board.simulateExternalCopy(text: "他アプリの新しいコピー")
        }

        let controller = PasteController(
            pasteboard: board,
            targetProvider: targetProvider,
            inputDriver: driver,
            restoreDelay: .milliseconds(10)
        )

        let outcome = await controller.paste(text: "音声入力の文", expectedTarget: target)
        XCTAssertEqual(outcome, .pasted(restoredClipboard: false))
        XCTAssertEqual(driver.sendCommandVCallCount, 1)
        // 他アプリの新しいコピーが上書きされずに残っていること。
        XCTAssertEqual(
            board.currentSnapshot.items.first?.entries.first?.data,
            Data("他アプリの新しいコピー".utf8)
        )
    }

    func testAbortsPasteWithoutOverwritingWhenExternalCopyHappensBeforeCommandV() async {
        let board = MockPasteboardClient()
        let target = PasteTarget(pid: 200, focusedElement: makeElement("field-A"))
        let targetProvider = MockTargetProvider(target: target)
        // 3回目の照合（一時テキスト書き込み後・⌘V送信直前）のタイミングで外部コピーが割り込む状況を模擬する。
        targetProvider.onQuery = { callIndex in
            if callIndex == 3 {
                board.simulateExternalCopy(text: "直前に割り込んだコピー")
            }
        }
        let driver = MockPasteInputDriver()
        let controller = PasteController(
            pasteboard: board,
            targetProvider: targetProvider,
            inputDriver: driver,
            restoreDelay: .milliseconds(5)
        )

        let outcome = await controller.paste(text: "音声入力の文", expectedTarget: target)
        XCTAssertEqual(outcome, .copiedFallback(reason: .clipboardOverwrittenBeforePaste))
        XCTAssertEqual(driver.sendCommandVCallCount, 0)
        XCTAssertEqual(
            board.currentSnapshot.items.first?.entries.first?.data,
            Data("直前に割り込んだコピー".utf8)
        )
    }

    func testTargetMismatchSkipsPasteAndCopiesTextToClipboard() async {
        let original = PasteboardSnapshot(items: [
            PasteboardItemSnapshot(entries: [
                PasteboardEntry(type: "public.utf8-plain-text", data: Data("元の内容".utf8)),
            ]),
        ])
        let board = MockPasteboardClient(initialSnapshot: original)
        let startTarget = PasteTarget(pid: 100, focusedElement: makeElement("field-1"))
        let movedTarget = PasteTarget(pid: 100, focusedElement: makeElement("field-2"))
        let driver = MockPasteInputDriver()

        let controller = PasteController(
            pasteboard: board,
            targetProvider: MockTargetProvider(target: movedTarget),
            inputDriver: driver,
            restoreDelay: .milliseconds(5)
        )

        let outcome = await controller.paste(text: "別欄へは貼らない文", expectedTarget: startTarget)
        XCTAssertEqual(outcome, .copiedFallback(reason: .targetChanged))
        XCTAssertEqual(driver.sendCommandVCallCount, 0)
        // 元の内容へ戻さず、認識結果がクリップボードに残ること。
        XCTAssertEqual(
            board.currentSnapshot.items.first?.entries.first?.data,
            Data("別欄へは貼らない文".utf8)
        )
    }

    func testTargetMatchingHandlesNilFocusedElementsCorrectly() {
        let a = PasteTarget(pid: 500, focusedElement: nil)
        let b = PasteTarget(pid: 500, focusedElement: nil)
        let c = PasteTarget(pid: 500, focusedElement: makeElement("input"))
        let d = PasteTarget(pid: 501, focusedElement: nil)

        XCTAssertTrue(a.matches(b))
        XCTAssertFalse(a.matches(c))
        XCTAssertFalse(a.matches(d))
    }

    func testWaitsWhileModifiersArePressedThenPastesOnceReleased() async {
        let board = MockPasteboardClient()
        let target = PasteTarget(pid: 300, focusedElement: makeElement("doc"))
        let driver = MockPasteInputDriver()
        // 最初の3回は修飾キー押下中、その後解放される。
        driver.modifierPollResponses = [true, true, true, false]
        driver.defaultModifiersPressed = false

        let controller = PasteController(
            pasteboard: board,
            targetProvider: MockTargetProvider(target: target),
            inputDriver: driver,
            modifierPollInterval: .milliseconds(5),
            modifierWaitTimeout: .milliseconds(200),
            restoreDelay: .milliseconds(5)
        )

        let outcome = await controller.paste(text: "解放後に貼る", expectedTarget: target)
        XCTAssertEqual(outcome, .pasted(restoredClipboard: true))
        XCTAssertEqual(driver.sendCommandVCallCount, 1)
    }

    func testModifiersHeldPastTimeoutFallsBackToClipboardCopy() async {
        let board = MockPasteboardClient()
        let target = PasteTarget(pid: 300, focusedElement: makeElement("doc"))
        let driver = MockPasteInputDriver()
        driver.defaultModifiersPressed = true

        let controller = PasteController(
            pasteboard: board,
            targetProvider: MockTargetProvider(target: target),
            inputDriver: driver,
            modifierPollInterval: .milliseconds(5),
            modifierWaitTimeout: .milliseconds(30),
            restoreDelay: .milliseconds(5)
        )

        let outcome = await controller.paste(text: "タイムアウト時の文", expectedTarget: target)
        XCTAssertEqual(outcome, .copiedFallback(reason: .modifiersTimeout))
        XCTAssertEqual(driver.sendCommandVCallCount, 0)
        XCTAssertEqual(
            board.currentSnapshot.items.first?.entries.first?.data,
            Data("タイムアウト時の文".utf8)
        )
    }

    func testEmptyClipboardIsRestoredCleanlyAfterPaste() async {
        let board = MockPasteboardClient(initialSnapshot: PasteboardSnapshot(items: []))
        let target = PasteTarget(pid: 400, focusedElement: makeElement("notes"))
        let driver = MockPasteInputDriver()

        let controller = PasteController(
            pasteboard: board,
            targetProvider: MockTargetProvider(target: target),
            inputDriver: driver,
            restoreDelay: .milliseconds(5)
        )

        let outcome = await controller.paste(text: "空からの貼り付け", expectedTarget: target)
        XCTAssertEqual(outcome, .pasted(restoredClipboard: true))
        XCTAssertEqual(driver.sendCommandVCallCount, 1)
        XCTAssertTrue(board.currentSnapshot.isEmpty)
    }

    func testEmptyTextIsSkippedWithoutTouchingClipboardOrCommandV() async {
        let original = PasteboardSnapshot(items: [
            PasteboardItemSnapshot(entries: [
                PasteboardEntry(type: "public.utf8-plain-text", data: Data("そのまま".utf8)),
            ]),
        ])
        let board = MockPasteboardClient(initialSnapshot: original)
        let beforeCount = board.changeCount
        let driver = MockPasteInputDriver()

        let controller = PasteController(
            pasteboard: board,
            targetProvider: MockTargetProvider(target: PasteTarget(pid: 1)),
            inputDriver: driver,
            restoreDelay: .milliseconds(5)
        )

        let outcome = await controller.paste(text: "", expectedTarget: PasteTarget(pid: 1))
        XCTAssertEqual(outcome, .skippedEmpty)
        XCTAssertEqual(driver.sendCommandVCallCount, 0)
        XCTAssertEqual(board.changeCount, beforeCount)
        XCTAssertEqual(board.currentSnapshot, original)
    }

    func testTransientMarkerConstantsMatchNSPasteboardConventions() {
        XCTAssertEqual(PasteboardMarker.transientType, "org.nspasteboard.TransientType")
        XCTAssertEqual(PasteboardMarker.autoGeneratedType, "org.nspasteboard.AutoGeneratedType")
    }

    func testSendCommandVFailureKeepsRecognizedTextOnClipboardInsteadOfRestoringOld() async {
        let original = PasteboardSnapshot(items: [
            PasteboardItemSnapshot(entries: [
                PasteboardEntry(type: "public.utf8-plain-text", data: Data("前のコピー".utf8)),
            ]),
        ])
        let board = MockPasteboardClient(initialSnapshot: original)
        let target = PasteTarget(pid: 700, focusedElement: makeElement("field"))
        let driver = MockPasteInputDriver()
        driver.sendCommandVResult = false

        let controller = PasteController(
            pasteboard: board,
            targetProvider: MockTargetProvider(target: target),
            inputDriver: driver,
            restoreDelay: .milliseconds(5)
        )

        let outcome = await controller.paste(text: "権限不足で貼れない文", expectedTarget: target)
        XCTAssertEqual(outcome, .copiedFallback(reason: .pasteCommandFailed))
        XCTAssertEqual(driver.sendCommandVCallCount, 1)
        // テキストを失わないようクリップボードに通常テキストとして残っていること。
        XCTAssertEqual(
            board.currentSnapshot.items.first?.entries.first?.data,
            Data("権限不足で貼れない文".utf8)
        )
        XCTAssertNil(
            board.currentSnapshot.items.first?.entries.first(where: { $0.type == "org.nspasteboard.TransientType" })
        )
    }
}
