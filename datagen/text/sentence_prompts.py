def render_item(i: int, spec: dict) -> str:
    """条件1件を、教師LLMへ渡す1〜2行の文字列にする。"""
    length_name, lo, hi = LENGTHS[spec["length"]]
    restate = f"あり（「{spec['restatement']}」を使う）" if spec["restatement"] else "なし"
    yn = lambda b: "あり" if b else "なし"  # noqa: E731
    if spec["no_change"]:
        return (
            f"条件{i}：用途={USECASES[spec['usecase']]}／話題のヒント={spec['topic']}"
            f"／長さ={length_name}（spokenで{lo}〜{hi}字）"
            "／整形の種類=変更なし（フィラー、言い直し、言いよどみ、繰り返し、英字の語を一切含めない。target は spoken に句読点を付けただけ）"
            f"／数字と単位={yn(spec['numbers'])}／口調={spec['tone']}\n用語：なし（英字で書く語を使わない）"
        )
    english = f"あり（候補：「{spec['english_phrase']}」）" if spec["english_phrase"] else "なし"
    line = (
        f"条件{i}：用途={USECASES[spec['usecase']]}／話題のヒント={spec['topic']}"
        f"／発話の形={'依頼' if spec['instruction_like'] else '自由'}"
        f"／長さ={length_name}（spokenで{lo}〜{hi}字）／フィラー={FILLER_LEVELS[spec['filler_level']]}"
        f"／言い直し={restate}／言いよどみ・繰り返し={yn(spec['disfluency'])}／列挙={'あり（spokenでは3つ以上の項目を口で順に挙げ、改行や「- 」は書かない。targetで箇条書きにする）' if spec['enumeration'] else 'なし'}"
        f"／数字と単位={yn(spec['numbers'])}／英語のフレーズ={english}／口調={spec['tone']}"
    )
    if spec["terms"]:
        line += "\n用語：" + "、".join(f"[[{t['surface']}|{t['reading']}]]" for t in spec["terms"])
    else:
        line += "\n用語：なし（英字で書く技術用語・製品名を使わない）"
    return line

